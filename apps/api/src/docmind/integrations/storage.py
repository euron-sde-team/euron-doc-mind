"""Where original files live: S3 (SSE-KMS) in every real deployment, local disk otherwise.

Keys are generated by DocMind (`workspaces/<id>/documents/<id>/original.<ext>`), never
taken from user input, and the local backend still refuses any key that could escape its
root directory.
"""

from __future__ import annotations

import os
import re
import tempfile
from collections.abc import AsyncIterator
from pathlib import Path
from typing import Protocol

import anyio
from botocore.exceptions import ClientError

from docmind.core.config import Settings
from docmind.core.errors import NotFoundError, ServiceUnavailableError
from docmind.integrations import aws

_SAFE_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9/_.-]{0,399}$")
CHUNK_SIZE = 1024 * 1024


class Storage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    def stream(self, key: str) -> AsyncIterator[bytes]: ...

    async def delete(self, key: str) -> None: ...

    async def check(self) -> None: ...


def document_key(workspace_id: object, document_id: object, extension: str) -> str:
    return f"workspaces/{workspace_id}/documents/{document_id}/original{extension}"


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        if not _SAFE_KEY.match(key) or ".." in key.split("/"):
            raise ValueError(f"unsafe storage key: {key!r}")
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"storage key escapes the root: {key!r}")
        return path

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Write then rename, so a reader never sees a half-written file.
            fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.replace(tmp, path)

        await anyio.to_thread.run_sync(write)

    async def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await anyio.Path(path).read_bytes()
        except FileNotFoundError as exc:
            raise NotFoundError("The original file is missing from storage.") from exc

    async def stream(self, key: str) -> AsyncIterator[bytes]:
        path = self._path(key)
        try:
            async with await anyio.open_file(path, "rb") as handle:
                while chunk := await handle.read(CHUNK_SIZE):
                    yield chunk
        except FileNotFoundError as exc:
            raise NotFoundError("The original file is missing from storage.") from exc

    async def delete(self, key: str) -> None:
        await anyio.to_thread.run_sync(lambda: self._path(key).unlink(missing_ok=True))

    async def check(self) -> None:
        await anyio.to_thread.run_sync(lambda: self.root.mkdir(parents=True, exist_ok=True))


class S3Storage:
    def __init__(self, settings: Settings) -> None:
        if not settings.s3_bucket:
            raise ValueError("S3_BUCKET is required for STORAGE_BACKEND=s3")
        self.bucket = settings.s3_bucket
        self.kms_key_id = settings.s3_kms_key_id
        self._client = aws.s3_client(settings)

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        kms_key_id = self.kms_key_id

        def upload() -> None:
            if kms_key_id:
                self._client.put_object(
                    Bucket=self.bucket,
                    Key=key,
                    Body=data,
                    ContentType=content_type,
                    ServerSideEncryption="aws:kms",
                    SSEKMSKeyId=kms_key_id,
                )
            else:
                self._client.put_object(
                    Bucket=self.bucket, Key=key, Body=data, ContentType=content_type
                )

        await anyio.to_thread.run_sync(upload)

    async def get(self, key: str) -> bytes:
        try:
            response = await anyio.to_thread.run_sync(
                lambda: self._client.get_object(Bucket=self.bucket, Key=key)
            )
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in {"NoSuchKey", "404"}:
                raise NotFoundError("The original file is missing from storage.") from exc
            raise
        body: bytes = await anyio.to_thread.run_sync(response["Body"].read)
        return body

    async def stream(self, key: str) -> AsyncIterator[bytes]:
        data = await self.get(key)
        for offset in range(0, len(data), CHUNK_SIZE):
            yield data[offset : offset + CHUNK_SIZE]

    async def delete(self, key: str) -> None:
        await anyio.to_thread.run_sync(
            lambda: self._client.delete_object(Bucket=self.bucket, Key=key)
        )

    async def check(self) -> None:
        try:
            await anyio.to_thread.run_sync(lambda: self._client.head_bucket(Bucket=self.bucket))
        except ClientError as exc:
            raise ServiceUnavailableError("The document bucket is not reachable.") from exc


def build_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    return LocalStorage(settings.storage_dir)
